/**
 * Builds the Super App's lib/core/miniapp/mini_app_registry.generated.dart: one
 * registration per Flutter mini app package, so the host can open it by any of
 * its ids. Pure (no file access), so the local injector and the production
 * build list (build-miniapps) produce exactly the same file.
 *
 * Partner-entered values (names, class names) end up in Dart source: strings are
 * escaped and class names must be plain Dart identifiers.
 */

export interface RegistryMiniApp {
  id?: string;
  appId?: string;
  name?: string;
  integrationConfig?: Record<string, any> | null;
  homeWidget?: { widgetClass?: string; verifiedClass?: string } | null;
}

export interface RegistryEntry {
  /** Dart package name in pubspec.yaml */
  packageName: string;
  app: RegistryMiniApp;
}

export const DART_PACKAGE_NAME = /^[a-z_][a-z0-9_]{0,63}$/;
const DART_IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]{0,127}$/;

/** A Dart single-quoted string literal. */
export function dartString(value: string): string {
  const escaped = String(value ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\$/g, '\\$')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n');
  return `'${escaped}'`;
}

/** A valid, lower-case Dart import prefix for a package name. */
export function dartImportPrefix(pkg: string): string {
  const safe = pkg.replace(/[^a-z0-9_]/g, '_');
  return /^[a-z_]/.test(safe) ? safe : `p_${safe}`;
}

/**
 * Sample packages whose entry widgets need their own arguments. Matched by exact
 * package name only: any other package goes through buildPackageWidget.
 */
const FIXED_ENTRIES: Record<string, (prefix: string) => string> = {
  sc_public_miniapp: (p) =>
    `${p}.PublicMiniAppEntry(onExit: () => safePop(context), passengerName: 'Super App Commuter', passTier: '30-Day Unlimited All-Access')`,
  sc_private_miniapp: (p) =>
    `${p}.MiniAppEntry(onExit: () => safePop(context), userName: 'Super App VIP Member', userTier: 'Gold Elite')`,
  ma_flutter_kyc: (p) =>
    `${p}.KycVerifierAppEntry(jwtToken: 'tok_live_superapp_session', userId: 'usr_fsa_verified', onExit: () => safePop(context))`,
};

export function renderMiniAppRegistry(entries: RegistryEntry[]): string {
  const imports = new Set<string>([
    "import 'package:flutter/material.dart';",
    "import 'package:go_router/go_router.dart';",
    "import 'mini_app_registry.dart';",
  ]);
  const registrations: string[] = [];

  for (const { packageName, app } of entries) {
    if (!DART_PACKAGE_NAME.test(packageName)) continue;
    const appId = app.appId || '';
    const nameSlug = (app.name || '').toLowerCase().replace(/\s+/g, '_');

    // Every package is imported under its own prefix so two packages that
    // both export `MiniAppEntry` never make the generated file ambiguous.
    const prefix = dartImportPrefix(packageName);
    imports.add(`import 'package:${packageName}/${packageName}.dart' as ${prefix};`);

    let widgetExpr: string;
    const fixed = FIXED_ENTRIES[packageName];
    if (fixed) {
      widgetExpr = fixed(prefix);
    } else {
      const requested = String(app.integrationConfig?.entryPoint || '').trim();
      const entryPoint = DART_IDENTIFIER.test(requested) ? requested : 'MiniAppEntry';
      // the helper hands the super app's token to constructors that accept it
      widgetExpr = `buildPackageWidget(${prefix}.${entryPoint}.new, {#onExit: () => safePop(context)}, superAppTokenProvider(context, ${dartString(appId)}))`;
    }

    const aliases = [
      packageName,
      appId,
      nameSlug,
      app.name || '',
      `miniapp_${nameSlug}_${(app.id || '').substring(0, 6)}`,
      app.id || '',
    ];
    const aliasList = `[
${aliases.map((a) => `    ${dartString(a)},`).join('\n')}
  ].where((s) => s.isNotEmpty).toList()`;
    let registration = `  MiniAppRegistry.registerAliases(${aliasList}, (context, arguments) => ${widgetExpr});`;

    // The Home widget was verified in the app's own package
    const widgetClass = app.homeWidget?.widgetClass;
    if (widgetClass && app.homeWidget?.verifiedClass === widgetClass && DART_IDENTIFIER.test(widgetClass)) {
      registration += `\n\n  MiniAppRegistry.registerWidgetAliases(${aliasList}, (context, onOpen) => buildPackageWidget(${prefix}.${widgetClass}.new, {#onOpen: onOpen}, superAppTokenProvider(context, ${dartString(appId)})));`;
    }
    registrations.push(registration);
  }

  return `// AUTO-GENERATED BY PubspecInjectorService - DO NOT EDIT MANUALLY
${Array.from(imports).join('\n')}

void registerDynamicGeneratedMiniApps() {
  void safePop(BuildContext context) {
    if (GoRouter.maybeOf(context) != null && GoRouter.of(context).canPop()) {
      GoRouter.of(context).pop();
    } else if (Navigator.of(context).canPop()) {
      Navigator.of(context).pop();
    }
  }

${registrations.join('\n\n')}
}
`;
}
